// One wording everywhere for where DSA test results came from.
//   hidden_tests          curated bank tests run in the isolated judge (verified)
//   ai_generated_samples  AI-written sample tests run in the same judge (not verified:
//                         the expected outputs themselves come from the AI)
export function testSummary({ test_source: source, tests_passed: passed, tests_total: total, judge_verdict: verdict } = {}) {
  if (!total || source === "none") return "";
  const counts = `${passed ?? 0}/${total}`;
  if (source === "hidden_tests") return `Hidden tests ${counts}${verdict ? ` · ${verdict}` : ""}`;
  return `AI sample tests ${counts}${verdict ? ` · ${verdict}` : ""} (not verified)`;
}

export const AI_SAMPLES_NOTE =
  "These sample tests and their expected outputs were generated by the AI. They run in the same isolated sandbox " +
  "as the curated bank, but they are not independently verified, so a failure can occasionally be the test's fault.";

export function crossCheckNote(status) {
  if (status === "cross_checked") return "Tests were cross-checked against an AI reference solution in the sandbox.";
  if (status === "reference_failed") return "The AI reference solution failed, so these tests could not be cross-checked.";
  return "These tests were not cross-checked against a reference solution.";
}
