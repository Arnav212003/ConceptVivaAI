"use client";

import { useState } from "react";
import Link from "next/link";
import { TierBadge } from "@/components/dsa/Badges";
import Workspace from "@/components/dsa/Workspace";
import { ErrorBanner, Notice } from "@/components/ui";
import useDsaWorkspace from "@/hooks/useDsaWorkspace";
import useJudgeStatus from "@/hooks/useJudgeStatus";
import useLocalHistory from "@/hooks/useLocalHistory";
import useSolutionVoice from "@/hooks/useSolutionVoice";
import { DSA_TOPICS, difficultyStyle } from "@/lib/difficulty";

export default function DSAPracticeCard() {
  // "verified" = curated 90-question bank (hidden tests when the judge is online).
  // "ai" = unlimited free-topic questions generated by Gemini, AI-review scored.
  const [mode, setMode] = useState("verified");
  const [topic, setTopic] = useState("Arrays");
  const [aiTopic, setAiTopic] = useState("");
  const [difficulty, setDifficulty] = useState("Easy");
  // Titles generated per AI topic this session, sent back so Gemini avoids repeats.
  const [recentAiTitles, setRecentAiTitles] = useState({});

  const workspace = useDsaWorkspace();
  const voice = useSolutionVoice(workspace.feedback);
  const judgeEnabled = useJudgeStatus();
  const history = useLocalHistory("conceptviva_dsa_history");

  const effectiveTopic = mode === "ai" ? aiTopic.trim() || "AI Topic" : topic;

  function resetFor(change) {
    change();
    voice.stop();
    workspace.reset();
  }

  async function generateProblem() {
    if (mode === "ai" && !aiTopic.trim()) {
      workspace.setError("Type a topic for AI Practice mode, for example Segment Trees, Tries or Union-Find.");
      return;
    }
    voice.stop();
    const topicKey = effectiveTopic.toLowerCase();
    const data = await workspace.loadProblem(
      mode === "ai" ? "generateAI" : "generate",
      {
        topic: effectiveTopic,
        difficulty,
        ...(mode === "ai" ? { recent_titles: recentAiTitles[topicKey] || [] } : {}),
      },
      mode === "ai" ? "ai_generated" : null
    );
    const newTitle = data?.problem_json?.title;
    if (mode === "ai" && newTitle) {
      setRecentAiTitles((prev) => ({ ...prev, [topicKey]: [newTitle, ...(prev[topicKey] || [])].slice(0, 15) }));
    }
  }

  async function submit() {
    if (!workspace.solution.trim()) {
      workspace.setError("Write your code first.");
      return;
    }
    const data = await workspace.submit({ topic: effectiveTopic, difficulty, mode: "Practice" });
    if (data) {
      const today = new Date();
      history.add({
        date: today.toLocaleDateString(),
        time: today.toLocaleTimeString(),
        mode: "Practice",
        topic: effectiveTopic,
        difficulty,
        problemName: workspace.problemData?.title || "DSA Problem",
        score: data.score,
        status: data.status || (data.score === null ? "Unavailable" : "Needs Improvement"),
      });
    }
  }

  async function revealSolution() {
    const confirmed = window.confirm(
      "This will reveal the solution and explanation. Your current code won't be scored or saved as an attempt. Continue?"
    );
    if (!confirmed) return;
    const data = await workspace.revealSolution({ topic: effectiveTopic, difficulty });
    // Clicking "stuck" means they want it explained, so start speaking right away.
    if (data) setTimeout(() => voice.explain(data), 300);
  }

  const modeNote =
    mode === "verified"
      ? judgeEnabled === false
        ? "Curated bank. The hidden-test judge is offline right now, so scoring uses AI review."
        : "Hidden-test scored by the isolated judge."
      : "AI-review scored: unlimited topics, no hidden tests.";

  return (
    <div className="mt-10 w-full max-w-6xl rounded-3xl border border-slate-700 bg-slate-950/70 p-4 shadow-2xl">
      <div className="mb-5 border-b border-slate-800 pb-5">
        <Link href="/dsa" className="text-sm font-semibold text-pink-300 hover:text-pink-200">
          ← Back to DSA Home
        </Link>
        <p className="mt-3 text-sm font-semibold uppercase tracking-widest text-pink-300">DSA Practice Mode</p>
        <h2 className="mt-2 text-3xl font-bold text-white">LeetCode-style AI Practice</h2>
        <p className="mt-1 text-base text-slate-400">
          Select topic and difficulty, generate one question, and submit for evaluation. Stuck? Reveal the
          solution and have the AI explain it out loud in English or Hindi.
        </p>
      </div>

      <div className="mb-5 rounded-2xl border border-slate-700 bg-slate-900/70 p-5">
        <div className="mb-4 flex flex-wrap items-center gap-2">
          {[
            ["verified", "✅ Verified Bank (90 Questions)", "bg-emerald-500"],
            ["ai", "🤖 AI Practice (Any Topic)", "bg-indigo-500"],
          ].map(([value, label, active]) => (
            <button
              key={value}
              onClick={() => resetFor(() => setMode(value))}
              aria-pressed={mode === value}
              className={`rounded-xl px-4 py-2 text-sm font-semibold transition ${
                mode === value ? `${active} text-white` : "bg-slate-800 text-slate-300 hover:bg-slate-700"
              }`}
            >
              {label}
            </button>
          ))}
          <p className="ml-1 text-xs text-slate-500">{modeNote}</p>
        </div>

        {mode === "verified" && judgeEnabled === false && (
          <div className="mb-4">
            <Notice tone="warn">
              ⚠️ The hidden-test judge is offline on this server. Curated questions still work, but submissions
              are scored by AI review (and labelled AI Generated) until the judge worker is running.
            </Notice>
          </div>
        )}

        <div className="grid gap-4 md:grid-cols-3">
          <div>
            <label htmlFor="dsa-topic" className="mb-2 block text-sm text-slate-300">DSA Topic</label>
            {mode === "verified" ? (
              <select
                id="dsa-topic"
                value={topic}
                onChange={(e) => resetFor(() => setTopic(e.target.value))}
                className="w-full rounded-xl border border-slate-700 bg-slate-950 px-4 py-3 text-base text-white outline-none"
              >
                {DSA_TOPICS.map((name) => (
                  <option key={name}>{name}</option>
                ))}
              </select>
            ) : (
              <input
                id="dsa-topic"
                type="text"
                value={aiTopic}
                maxLength={200}
                onChange={(e) => setAiTopic(e.target.value)}
                placeholder="e.g. Segment Trees, Tries, Union-Find"
                className="w-full rounded-xl border border-indigo-700 bg-slate-950 px-4 py-3 text-base text-white outline-none placeholder:text-slate-600"
              />
            )}
          </div>

          <div>
            <label htmlFor="dsa-difficulty" className="mb-2 block text-sm text-slate-300">Difficulty</label>
            <select
              id="dsa-difficulty"
              value={difficulty}
              onChange={(e) => resetFor(() => setDifficulty(e.target.value))}
              className="w-full rounded-xl border border-slate-700 bg-slate-950 px-4 py-3 text-base text-white outline-none"
            >
              <option>Easy</option>
              <option>Medium</option>
              <option>Hard</option>
            </select>
          </div>

          <div className="flex items-end">
            <button
              onClick={generateProblem}
              disabled={workspace.loading.problem}
              className={`w-full rounded-xl px-6 py-3 text-base font-semibold text-white transition disabled:opacity-60 ${
                mode === "ai" ? "bg-indigo-500 hover:bg-indigo-600" : "bg-pink-500 hover:bg-pink-600"
              }`}
            >
              {workspace.loading.problem ? "Generating..." : "Generate Problem"}
            </button>
          </div>
        </div>
      </div>

      {workspace.error && (
        <div className="mb-5">
          <ErrorBanner message={workspace.error} onDismiss={() => workspace.setError("")} />
        </div>
      )}

      <Workspace
        workspace={workspace}
        voice={voice}
        onRun={() => workspace.run({ topic: effectiveTopic, difficulty, judgeEnabled: judgeEnabled && mode === "verified" })}
        onSubmit={submit}
        onRevealSolution={revealSolution}
        header={
          <>
            <div className="min-w-0">
              <h3 className="text-lg font-semibold text-white">Problem Statement</h3>
              <p className="mt-1 truncate text-sm text-slate-400">
                Topic: {effectiveTopic} · <span className={difficultyStyle(difficulty).text}>{difficulty}</span>
              </p>
            </div>
            <TierBadge tier={workspace.tier} />
          </>
        }
      />

      <div className="mt-6 text-center">
        <Link href="/dsa/history" className="text-sm font-semibold text-cyan-300 hover:text-cyan-200">
          View full practice history →
        </Link>
      </div>
    </div>
  );
}
