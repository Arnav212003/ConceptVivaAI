def get_dsa_mock_set(topic="Arrays", difficulty="Mixed", count=10):
    import random

    topic = topic.lower().strip()
    difficulty = difficulty.lower().strip()

    filtered_questions = [
        question
        for question in DSA_QUESTION_BANK
        if topic in question["topic"].lower()
    ]

    if difficulty != "mixed":
        filtered_questions = [
            question
            for question in filtered_questions
            if question["difficulty"].lower() == difficulty
        ]

    if count >= len(filtered_questions):
        return filtered_questions

    return random.sample(filtered_questions, count)


def get_dsa_practice_question(topic="Arrays", difficulty="Mixed"):
    import random

    topic = topic.lower().strip()
    difficulty = difficulty.lower().strip()

    filtered_questions = [
        question
        for question in DSA_QUESTION_BANK
        if topic in question["topic"].lower()
    ]

    if difficulty != "mixed":
        filtered_questions = [
            question
            for question in filtered_questions
            if question["difficulty"].lower() == difficulty
        ]

    if not filtered_questions:
        return None

    return random.choice(filtered_questions)